#!/usr/bin/env python3
"""Part B - availability calculation for the synthetic AITU platform.

Usage:  python3 scripts/availability.py            (prints Markdown)
        python3 scripts/availability.py > results/availability.md

Formulas
  parallel (n independent replicas): R = 1 - (1 - r)^n
  series:                            R = R1 * R2 * ... * Rk
"""
from math import prod

HOURS_PER_YEAR = 365 * 24          # 8760 h
MIN_PER_MONTH = 30 * 24 * 60       # 43200 min
TARGET = 0.999

# Synthetic component availability from the assignment.
COMPONENTS = {
    "Load Balancer": 0.9995,
    "API Gateway": 0.9990,
    "Auth instance": 0.9950,
    "Course instance": 0.9950,
    "Registration instance": 0.9950,
    "Database node": 0.9970,
}


def parallel(r, n):
    return 1 - (1 - r) ** n


def pct(x, digits=4):
    return f"{x * 100:.{digits}f}%"


def downtime(a):
    return (1 - a) * HOURS_PER_YEAR, (1 - a) * MIN_PER_MONTH


def design(lb=1, gw=1, auth=2, course=2, reg=2, db=2):
    """Return {subsystem: availability} for a given replica count per tier."""
    c = COMPONENTS
    return {
        "Load Balancer": parallel(c["Load Balancer"], lb),
        "API Gateway": parallel(c["API Gateway"], gw),
        "Auth": parallel(c["Auth instance"], auth),
        "Course": parallel(c["Course instance"], course),
        "Registration": parallel(c["Registration instance"], reg),
        "Database": parallel(c["Database node"], db),
    }


def end_to_end(subsystems):
    return prod(subsystems.values())


def main():
    base = design()
    e2e = end_to_end(base)

    print("# Part B - Availability calculation (generated by scripts/availability.py)\n")
    print("## 1. Redundant subsystems (2 independent replicas)\n")
    print("| Subsystem | Configuration | Calculation | Availability |")
    print("|---|---|---|---|")
    for name, key, conf in [
        ("Auth", "Auth instance", "2 replicas"),
        ("Course", "Course instance", "2 replicas"),
        ("Registration", "Registration instance", "2 replicas"),
        ("Database", "Database node", "2 nodes"),
    ]:
        r = COMPONENTS[key]
        print(f"| {name} | {conf} | 1 - (1 - {r})^2 = 1 - {1 - r:.3f}^2 = 1 - {(1 - r) ** 2:.6f} "
              f"| **{pct(parallel(r, 2))}** |")
    print(f"| Load Balancer | 1 instance (no redundancy) | given | {pct(base['Load Balancer'])} |")
    print(f"| API Gateway | 1 instance (no redundancy) | given | {pct(base['API Gateway'])} |")
    terms = " x ".join(f"{v:.6f}" for v in base.values())
    print(f"| **End-to-end** | Series LB -> GW -> Auth -> Course -> Registration -> DB "
          f"| {terms} | **{pct(e2e)}** |\n")

    y, m = downtime(e2e)
    ty, tm = downtime(TARGET)
    print("## 2. Does the design meet 99.9%?\n")
    print(f"- End-to-end availability = **{pct(e2e)}** "
          f"(expected downtime {y:.1f} h/year, {m:.1f} min/month).")
    print(f"- Target 99.9% allows {ty:.2f} h/year, {tm:.1f} min/month.")
    print(f"- Result: **{'MEETS' if e2e >= TARGET else 'DOES NOT MEET'}** the target "
          f"(short by {(TARGET - e2e) * 100:.4f} percentage points).\n")

    print("## 3. Bottleneck (unavailability contribution of each subsystem)\n")
    print("| Subsystem | Availability | Unavailability | Share of total downtime |")
    print("|---|---|---|---|")
    total_u = sum(1 - v for v in base.values())
    for name, v in sorted(base.items(), key=lambda kv: kv[1]):
        print(f"| {name} | {pct(v)} | {(1 - v) * 100:.4f}% | {(1 - v) / total_u * 100:.1f}% |")
    print("\nThe API Gateway is a single instance at 99.90%: on its own it already uses the whole\n"
          "99.9% budget, so any other component in series pushes the system below target.\n"
          "LB + Gateway together cause ~94% of the expected downtime.\n")

    print("## 4. What-if: which redundancy change has the largest effect?\n")
    print("| Change | End-to-end | Downtime h/year | Meets 99.9%? |")
    print("|---|---|---|---|")
    scenarios = [
        ("Baseline (as given)", design()),
        ("+1 Auth / Course / Registration replica (3 each)", design(auth=3, course=3, reg=3)),
        ("+1 Database node (3 nodes)", design(db=3)),
        ("2 Load Balancers", design(lb=2)),
        ("**2 API Gateways**", design(gw=2)),
        ("2 Load Balancers + 2 API Gateways", design(lb=2, gw=2)),
    ]
    for label, s in scenarios:
        a = end_to_end(s)
        print(f"| {label} | {pct(a)} | {downtime(a)[0]:.2f} | {'yes' if a >= TARGET else 'no'} |")
    print("\nAdding a second API Gateway replica has the largest single effect "
          "(about 13.9 -> 5.1 h/year of downtime) and is enough to meet 99.9%. "
          "Adding replicas to the already-redundant services barely changes the result.")


if __name__ == "__main__":
    main()
